/**
 * Assert that a fixture satisfies its generated contract schema, and say WHICH
 * field broke when it does not. A bare `false` would tell a developer that
 * something drifted, not what drifted.
 */
function expectMatchesContract(schema: z.ZodTypeAny, value: unknown, label: string) {
  const result = schema.safeParse(value);
  const detail = result.success
    ? ''
    : ` -- ${result.error.issues
        .map((issue) => `${issue.path.join('.') || '<root>'}: ${issue.message}`)
        .join('; ')}`;
  expect(result.success, `${label} must satisfy the API contract${detail}`).toBe(true);
}

